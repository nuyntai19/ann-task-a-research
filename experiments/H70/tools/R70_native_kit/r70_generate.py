#!/usr/bin/env python3
"""Generate a source-extracted TwoTierLSHGraph in an isolated pinned PiPNN worktree.

This does NOT modify graph.h or the original PiPNN source checkout.
The original merge_neighbors implementation is copied from the pinned source
with only pointer relocation and a 64->160 promotion gate added.
"""
import argparse
import pathlib
import re
import subprocess
import sys

COMMIT = '443a328dc71a3b7be753d52ca2b3c9a4ba77f3fd'
BLOB = '7c5b8c1196a3ad741dfd22fe8f35b72acae2b19f'

def git(repo, *args):
    return subprocess.check_output(['git','-C',str(repo),*args], text=True).strip()

def fail(s):
    raise SystemExit('R70_BLOCKED ' + s)

def extract_braced(src, start_index):
    brace=src.index('{',start_index)
    nest=0
    for i in range(brace,len(src)):
        if src[i]=='{': nest+=1
        elif src[i]=='}':
            nest-=1
            if nest==0:
                return src[start_index:i+1]
    fail('unbalanced source')

def main():
    p=argparse.ArgumentParser()
    p.add_argument('--worktree', required=True)
    p.add_argument('--force', action='store_true',help='Allow replacing only generated R70 files')
    a=p.parse_args()
    w=pathlib.Path(a.worktree).expanduser().resolve()
    if git(w,'rev-parse','HEAD')!=COMMIT: fail('wrong pinned commit')
    original=w/'algorithms/utils/graph.h'
    if git(w,'hash-object','algorithms/utils/graph.h')!=BLOB: fail('graph.h is not pinned source')
    orig=original.read_text()
    pivot=orig.index('struct LSHGraph {')
    sig='template<typename rangeType>\nvoid merge_neighbors(const size_t i, const rangeType& r) {'
    if orig.count(sig)!=1: fail('unexpected merge_neighbors signature')
    original_merge=extract_braced(orig,orig.index(sig,pivot))
    pattern=(r'  const size_t base\s*= i \* \(kMaxDegree \+ 1\);\s*'
             r'T\* const sentinel\s*= &tables\[base\];[^\n]*\n\s*'
             r'T\* const begin\s*= &tables\[base \+ 1\];')
    replacement='  T* sentinel = row_ptr(i); // active pointer; updated after promotion\n  T* begin = sentinel + 1;'
    copied,n=re.subn(pattern,replacement,original_merge,count=1)
    if n!=1: fail('source pointer block mismatch')
    # A new hash is actually inserted only after the collision check. This is
    # the precise point to promote; duplicate hashes must not trigger promotion.
    guard='    if (deg < kMaxDegree) {'
    if copied.count(guard)!=1: fail('insertion branch mismatch')
    promote='''    if (deg == kSmallCapacity && !is_promoted(i)) {
      T* large = new_full_row(); // stable pointer from the slab arena
      std::copy_n(sentinel, deg + 1, large); // sentinel and all active candidates
      active_rows_[i] = large; // publication occurs under locks[i]
      sentinel = large;
      begin = large + 1;
      end = begin + deg;
      pos_ptr = std::lower_bound(begin, end, cand_hash, cmp);
      pos = static_cast<size_t>(pos_ptr - begin);
      // Cached worst state was copied byte-for-byte and is unchanged.
    }

'''
    copied=copied.replace(guard,promote+guard)
    if 'tables' in copied: fail('merge body still has direct tables reference')
    if 'locks[i].Lock()' not in copied or 'locks[i].Unlock()' not in copied: fail('missing lock')
    # Source signature unchanged for merge_neighbors; other methods match stock API.
    header='''// Generated by r70_generate.py from pinned PiPNN source.
// This file is research-only, and must never replace algorithms/utils/graph.h.
#pragma once
#include <atomic>
#include <memory>
#include <mutex>
#include <new>
#include <stdexcept>
#include <cstdlib>
#include <cstring>
#include <algorithm>
#include <iostream>
#include "utils/graph.h"

namespace parlayANN {

template <typename indexType_, typename distanceType_, typename sketchHash>
struct TwoTierLSHGraph {
  using indexType = indexType_;
  using distanceType = distanceType_;
  using T = LSHCandidate<indexType, distanceType>;
  static constexpr size_t kSmallCapacity = 64;
  static constexpr size_t kChunkRows = 1024;

  size_t n;
  sketchHash &H;
  size_t kMaxDegree;
  absl::Mutex* locks = nullptr;
  T* small_rows_ = nullptr;
  T** active_rows_ = nullptr;
  std::unique_ptr<std::atomic<T*>[]> chunks_;
  size_t max_chunks_ = 0;
  std::atomic<size_t> next_promoted_{0};
  std::mutex chunk_lock_;

  TwoTierLSHGraph(size_t count, size_t cap, sketchHash &hash, bool allocate=true)
      : n(count), H(hash), kMaxDegree(cap) {
    if (cap <= kSmallCapacity || cap > 65535)
      throw std::invalid_argument("R70: logical cap must be in (64, 65535]");
    if (allocate) allocate_graph(count);
  }
  TwoTierLSHGraph(const TwoTierLSHGraph&) = delete;
  TwoTierLSHGraph& operator=(const TwoTierLSHGraph&) = delete;

  static T* aligned_rows(size_t bytes, size_t align) {
    size_t rounded = (bytes + align - 1) / align * align;
    if (rounded == 0) rounded = align;
    auto* ptr = static_cast<T*>(std::aligned_alloc(align, rounded));
    if (!ptr) throw std::bad_alloc();
    return ptr;
  }

  void allocate_graph(size_t count) {
    if (small_rows_ || locks || active_rows_ || chunks_)
      throw std::logic_error("R70: allocate_graph called more than once");
    if (count != n || count == 0) throw std::invalid_argument("R70: invalid node count");
    constexpr size_t alignment=1UL<<21;
    small_rows_=aligned_rows(n*(kSmallCapacity+1)*sizeof(T), alignment);
    (void)madvise(small_rows_, n*(kSmallCapacity+1)*sizeof(T), MADV_HUGEPAGE);
    active_rows_=new T*[n];
    locks = new absl::Mutex[n];
    max_chunks_=(n+kChunkRows-1)/kChunkRows;
    chunks_=std::make_unique<std::atomic<T*>[]>(max_chunks_);
    for (size_t c=0;c<max_chunks_;++c) chunks_[c].store(nullptr);
    parlay::parallel_for(0,n,[&](size_t i){
      T* row=small_rows_+i*(kSmallCapacity+1);
      row[0].point_id=0;
      row[0].norm=Eigen::bfloat16(0);
      row[0].hash=0;
      active_rows_[i]=row;
    });
  }
  size_t size() const {return n;}
  T* row_ptr(size_t i) const {return active_rows_[i];}
  bool is_promoted(size_t i) const {
    return active_rows_[i] != small_rows_ + i*(kSmallCapacity+1);
  }
  size_t promoted_rows() const {return next_promoted_.load();}

  T* new_full_row() {
    const size_t ordinal=next_promoted_.fetch_add(1);
    if (ordinal >= n) throw std::overflow_error("R70: too many promoted rows");
    const size_t chunk=ordinal/kChunkRows;
    const size_t slot=ordinal%kChunkRows;
    T* p=chunks_[chunk].load(std::memory_order_acquire);
    if (!p) {
      std::lock_guard<std::mutex> lock(chunk_lock_);
      p=chunks_[chunk].load(std::memory_order_relaxed);
      if (!p) {
        p=aligned_rows(kChunkRows*(kMaxDegree+1)*sizeof(T),64);
        chunks_[chunk].store(p,std::memory_order_release);
      }
    }
    return p + slot*(kMaxDegree+1);
  }

  indexType &degree(size_t i) {return row_ptr(i)[0].point_id;}
  Eigen::bfloat16 &get_furthest(size_t i) {return row_ptr(i)[0].norm;}
  size_t get_furthest_index(size_t i) const {return size_t(row_ptr(i)[0].hash);}
  T &get_candidate(size_t i, size_t j) {return row_ptr(i)[1+j];}
  T *candidates_begin(size_t i) {return row_ptr(i)+1;}
  T *candidates_end(size_t i) {return row_ptr(i)+1+degree(i);}
  absl::Span<T> Neighbors(size_t i) {return absl::Span<T>(row_ptr(i)+1, degree(i));}
  absl::Span<const T> Neighbors(size_t i) const {return absl::Span<const T>(row_ptr(i)+1, row_ptr(i)[0].point_id);}
  void finalize() {}

'''
    footer='''
  ~TwoTierLSHGraph(){
    if (chunks_) for(size_t i=0;i<max_chunks_;++i) std::free(chunks_[i].load());
    delete[] locks;
    delete[] active_rows_;
    std::free(small_rows_);
  }
};
} // namespace parlayANN
'''
    generated=header+copied+'\n'+footer
    dst=w/'algorithms/utils/r70_two_tier_lshgraph.h'
    if dst.exists() and not a.force: fail('generated header already exists (use --force if explicitly replacing)')
    dst.write_text(generated)
    cm=w/'algorithms/PipNN/CMakeLists.txt'
    spec='''
# R70 research-only native correctness/microbench target (isolated worktree)
add_executable(r70_native_tests r70_native_tests.cc)
target_link_libraries(r70_native_tests PRIVATE parlay ParlayANN
  Eigen3::Eigen absl::synchronization absl::flat_hash_set absl::span hwy hwy_contrib)
target_include_directories(r70_native_tests PRIVATE ../bench ../../external/Parallel-KMeans/seeding)
'''
    source=cm.read_text()
    if 'add_executable(r70_native_tests' not in source:
        cm.write_text(source+'\n'+spec)
    dsttest=w/'algorithms/PipNN/r70_native_tests.cc'
    inputtest=pathlib.Path(__file__).with_name('r70_native_tests.cc')
    if dsttest.exists() and not a.force: fail('generated test already exists')
    dsttest.write_bytes(inputtest.read_bytes())
    print('R70_GENERATOR_PASS_SOURCE_PINNED',COMMIT)
    print('R70_GENERATOR_PASS_EXACT_ORIGINAL_MERGE_EXTRACTED')
    print('R70_GENERATED_HEADER',dst)
    print('R70_GENERATED_HARNESS',dsttest)
    print('R70_ONLY_ISOLATED_WORKTREE_MODIFIED')
    print('R70_NEEDS_NATIVE_COMPILE_TEST_NOT_CLAIMED_PASS')

if __name__=='__main__': main()

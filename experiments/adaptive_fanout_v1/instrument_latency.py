#!/usr/bin/env python3
"""Generate local native headers with timers around the two qsearchAll query callbacks."""
import argparse
import hashlib
from pathlib import Path


def instrument(source):
    # Patch only qsearchAll; keep the query algorithm, results and parallel
    # scheduler unchanged. Fail if an upstream edit invalidates these anchors.
    start = source.index("\nqsearchAll(const PointRange &Query_Points,")
    end_marker = "\n  return all_neighbors;\n}"
    end = source.index(end_marker, start) + len(end_marker)
    original = source[start:end]
    needle = "    parlay::parallel_for(0, Query_Points.size(), [&](size_t i) {\n"
    if original.count(needle) != 2:
        raise ValueError("Expected exactly two native qsearchAll query callbacks")
    replacement = original.replace(needle, needle + "      local_latency::QueryTimer query_timer(i);\n")
    return '#include "latency_probe.h"\n' + source[:start] + replacement + source[end:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    for name in ("beamSearch.h", "check_nn_recall.h"):
        original = (args.source / name).read_text()
        content = instrument(original) if name == "beamSearch.h" else original
        if name == "check_nn_recall.h":
            assert content.count("numCorrect += 1;") == 2
            content = content.replace("numCorrect += 1;", "numCorrect += 1; local_latency::query_hits[i] += 1;")
        header = ("// Generated by instrument_latency.py from native R86. Original SHA256: "
                  + hashlib.sha256(original.encode()).hexdigest() + "\n")
        target = args.output / name
        if not target.exists() or target.read_text() != header + content:
            target.write_text(header + content)


if __name__ == "__main__":
    main()
